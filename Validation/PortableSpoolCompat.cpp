#include "DiskSnapshotSpool.h"
#include <filesystem>
#include <string>
int main(int argc,char **argv) {
    if(argc!=2)return 1;
    fsyn::DiskSnapshotSpool spool;
    if(!spool.Open(std::filesystem::path(argv[1])))return 2;
    for(int i=0;i<5000;++i) {
        const auto p=std::string("a/sub/")+std::to_string(i)+".xml";
        if(!spool.Append({p,std::string(40,'a'),static_cast<uint64_t>(i),i}))return 3;
    }
    if(!spool.Finish())return 4;
    spool.Close(false); // Keep the generated bytes for cross-version comparison.
    return 0;
}
